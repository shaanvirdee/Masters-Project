# Plot 4: Cross-Validation Distribution
ax4 = axes[1, 1]
ax4.boxplot([cv_train_scores, cv_test_scores], labels=['Train R²', 'Test R²'])
ax4.scatter([1]*len(cv_train_scores), cv_train_scores, alpha=0.4, color='blue', s=20)
ax4.scatter([2]*len(cv_test_scores), cv_test_scores, alpha=0.4, color='red', s=20)
