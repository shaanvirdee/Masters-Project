def predict_hardness(power, speed, sh, ht):
    """
    Predict hardness for new input parameters.

    Parameters:
    - power: Power value (e.g., 120-210)
    - speed: Speed value (e.g., 600-1200)
    - sh: SH parameter (True/False or 1/0)
    - ht: HT parameter (True/False or 1/0)

    Returns:
    - Predicted hardness value
    """
    X_new = np.array([[power, speed, int(sh), int(ht)]])
    X_scaled = scaler_final.transform(X_new)
    X_poly = poly_final.transform(X_scaled)
    return model_final.predict(X_poly)[0]

