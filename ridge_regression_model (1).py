ax2.set_title('Residual Plot (Test Set)', fontsize=12, fontweight='bold')
ax2.grid(True, alpha=0.3)

# Plot 3: Feature Importance
ax3 = axes[1, 0]
names = [x[0] for x in coef_importance]
values = [x[1] for x in coef_importance]
colors = ['green' if v > 0 else 'red' for v in values]
ax3.barh(range(len(names)), values, color=colors, alpha=0.7, edgecolor='black')
ax3.set_yticks(range(len(names)))
