# 9. PREDICTION FUNCTION
# =============================================================================
def predict_sqrt_area(power, speed, sh, ht, verbose=True):
    """
    Predict the √Area defect size distribution for a given process condition.

    The model outputs the Top-10 mean √Area directly. A lognormal distribution
    is then reconstructed using:
      - log_mean: back-calculated from top-10 mean via empirical offset
      - log_std:  pooled within-part std from all 56 parts (fixed at 0.677)

    Parameters
    ----------
    power : int/float  Laser power in W         — trained on 120, 150, 180, 210
    speed : int/float  Scan speed in mm/s       — trained on 600, 800, 1000, 1200
    sh    : int/bool   Substrate Heating         — 0=OFF, 1=ON
    ht    : int/bool   Heat Treatment            — 0=OFF, 1=ON

    Returns dict with predicted top-10 mean, mean, median, P90, P95, P99,
    P99.9 in μm (units of √Area), plus log_mean and log_std.
    """
    sh, ht   = int(sh), int(ht)
    cond_lbl = COND_LABELS.get((sh, ht), f'SH={sh},HT={ht}')

    X_new    = np.array([[power, speed, sh, ht]])
    log_topk = model_f.predict(poly_f.transform(scaler_f.transform(X_new)))[0]
    log_mu   = log_topk - topk_offset
    log_sig  = pooled_log_std
    dist     = lognorm(s=log_sig, scale=np.exp(log_mu))

    result = {
        f'top{K}_mean_um': np.exp(log_topk),
        'log_mean':         log_mu,
        'log_std':          log_sig,
        'mean_um':          dist.mean(),
        'median_um':        dist.median(),
        'P90_um':           dist.ppf(0.90),
        'P95_um':           dist.ppf(0.95),
        'P99_um':           dist.ppf(0.99),
        'P999_um':          dist.ppf(0.999),
    }

    if verbose:
        print(f"\n{'─'*60}")
        print(f"  Power={power}W  Speed={speed}mm/s  "
              f"SH={'ON' if sh else 'OFF'}  HT={'ON' if ht else 'OFF'}"
              f"  [{cond_lbl}]")
        print(f"{'─'*60}")
        print(f"  Top-{K} Mean : {result[f'top{K}_mean_um']:>10.2f} μm  "
              f"← direct model output")
        print(f"  Mean        : {result['mean_um']:>10.2f} μm")
        print(f"  Median      : {result['median_um']:>10.2f} μm")
        print(f"  P90         : {result['P90_um']:>10.2f} μm")
        print(f"  P95         : {result['P95_um']:>10.2f} μm")
        print(f"  P99         : {result['P99_um']:>10.2f} μm")
        print(f"  P99.9       : {result['P999_um']:>10.2f} μm")

    return result


